            UNION ALL SELECT 'HRMS_ACTIONS_MODULE_NN' FROM dual
            UNION ALL SELECT 'HRMS_ACTIONS_CODE_NN' FROM dual
            UNION ALL SELECT 'HRMS_ACTIONS_ACTIVE_NN' FROM dual
            UNION ALL SELECT 'HRMS_ACTIONS_CREATED_BY_NN' FROM dual
            UNION ALL SELECT 'HRMS_ACTIONS_CREATED_AT_NN' FROM dual
            UNION ALL SELECT 'HRMS_ACTIONS_PK' FROM dual
            UNION ALL SELECT 'HRMS_ACTIONS_ACTIVE_CK' FROM dual
