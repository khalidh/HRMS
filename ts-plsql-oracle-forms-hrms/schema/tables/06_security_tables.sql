MERGE INTO HRMS.HRMS_ROLES target
USING (
    SELECT 'EMPLOYEE' role_code, 'Employee' role_name, 'Self-service employee access.' role_description FROM dual
    UNION ALL SELECT 'MANAGER', 'Manager', 'Team access within current and delegated scope.' FROM dual
    UNION ALL SELECT 'HR', 'Human Resources', 'Human resources operations.' FROM dual
    UNION ALL SELECT 'PAYROLL', 'Payroll', 'Payroll operations.' FROM dual
    UNION ALL SELECT 'ADMIN', 'Administrator', 'Technical administration without implicit access to sensitive business data.' FROM dual
    UNION ALL SELECT 'AUDITOR', 'Auditor', 'Read-only access to explicitly authorized audit data.' FROM dual
) src
ON (target.ROLE_CODE = src.ROLE_CODE)
WHEN NOT MATCHED THEN
    INSERT (ROLE_CODE, ROLE_NAME, ROLE_DESCRIPTION)
    VALUES (src.ROLE_CODE, src.ROLE_NAME, src.ROLE_DESCRIPTION);

MERGE INTO HRMS.HRMS_ACTIONS target
