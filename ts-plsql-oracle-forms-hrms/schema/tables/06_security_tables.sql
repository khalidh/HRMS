    v_missing_constraints PLS_INTEGER;
    v_missing_tables      PLS_INTEGER;
BEGIN
    SELECT COUNT(*)
      INTO v_missing_tables
      FROM (
            SELECT 'HRMS_USER_IDENTITIES' table_name FROM dual
            UNION ALL SELECT 'HRMS_ROLES' FROM dual
            UNION ALL SELECT 'HRMS_ACTIONS' FROM dual
            UNION ALL SELECT 'HRMS_ROLE_ACTIONS' FROM dual
            UNION ALL SELECT 'HRMS_USER_ROLES' FROM dual
            UNION ALL SELECT 'HRMS_EMPLOYEE_SCOPE_DELEGATIONS' FROM dual
           ) expected
     WHERE NOT EXISTS (
           SELECT 1
             FROM ALL_TABLES actual
            WHERE actual.OWNER = 'HRMS'
              AND actual.TABLE_NAME = expected.table_name
       );

    IF v_missing_tables > 0 THEN
        RAISE_APPLICATION_ERROR(-20097, 'HRMS security tables are incomplete.');
    END IF;

    SELECT COUNT(*)
      INTO v_missing_constraints
      FROM (
            SELECT 'HRMS_USER_IDENTITIES_SUBJECT_NN' constraint_name FROM dual
            UNION ALL SELECT 'HRMS_USER_IDENTITIES_EMP_NN' FROM dual
            UNION ALL SELECT 'HRMS_USER_IDENTITIES_ACTIVE_NN' FROM dual
