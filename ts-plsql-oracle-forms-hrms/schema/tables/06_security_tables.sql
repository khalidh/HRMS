    UNION ALL SELECT 'EMPLOYEE', 'TERMINATE', 'Terminate an employee.' FROM dual
    UNION ALL SELECT 'EMPLOYEE', 'EXPORT', 'Export authorized employee data.' FROM dual
    UNION ALL SELECT 'ORGANIZATION', 'VIEW', 'View organizational data.' FROM dual
    UNION ALL SELECT 'ORGANIZATION', 'UPDATE', 'Update organizational data.' FROM dual
    UNION ALL SELECT 'LEAVE', 'VIEW', 'View authorized leave data.' FROM dual
    UNION ALL SELECT 'LEAVE', 'CREATE', 'Submit leave requests.' FROM dual
    UNION ALL SELECT 'LEAVE', 'APPROVE', 'Approve leave requests.' FROM dual
    UNION ALL SELECT 'LEAVE', 'REJECT', 'Reject leave requests.' FROM dual
    UNION ALL SELECT 'LEAVE', 'CANCEL', 'Cancel leave requests.' FROM dual
    UNION ALL SELECT 'LEAVE', 'EXPORT', 'Export authorized leave data.' FROM dual
    UNION ALL SELECT 'PAYROLL', 'VIEW', 'View authorized payroll data.' FROM dual
    UNION ALL SELECT 'PAYROLL', 'CALCULATE', 'Calculate payroll.' FROM dual
    UNION ALL SELECT 'PAYROLL', 'APPROVE', 'Approve payroll.' FROM dual
    UNION ALL SELECT 'PAYROLL', 'PAY', 'Record payroll payment.' FROM dual
    UNION ALL SELECT 'PAYROLL', 'REVERSE', 'Reverse a payroll run.' FROM dual
    UNION ALL SELECT 'PAYROLL', 'EXPORT', 'Export authorized payroll data.' FROM dual
    UNION ALL SELECT 'PERFORMANCE', 'VIEW', 'View authorized performance data.' FROM dual
    UNION ALL SELECT 'PERFORMANCE', 'CREATE', 'Create performance records.' FROM dual
    UNION ALL SELECT 'PERFORMANCE', 'UPDATE', 'Update performance records.' FROM dual
    UNION ALL SELECT 'PERFORMANCE', 'APPROVE', 'Approve performance records.' FROM dual
    UNION ALL SELECT 'PERFORMANCE', 'EXPORT', 'Export authorized performance data.' FROM dual
    UNION ALL SELECT 'ADMIN', 'VIEW', 'View technical administration data.' FROM dual
    UNION ALL SELECT 'ADMIN', 'UPDATE', 'Update technical administration data.' FROM dual
    UNION ALL SELECT 'ADMIN', 'MANAGE', 'Manage application roles and configuration.' FROM dual
    UNION ALL SELECT 'ADMIN', 'EXECUTE', 'Execute authorized operational jobs.' FROM dual
    UNION ALL SELECT 'AUDIT', 'VIEW', 'View authorized audit data.' FROM dual
    UNION ALL SELECT 'AUDIT', 'EXPORT', 'Export authorized audit data.' FROM dual
    UNION ALL SELECT 'REPORT', 'VIEW', 'View authorized reports.' FROM dual
    UNION ALL SELECT 'REPORT', 'EXPORT', 'Export authorized reports.' FROM dual
) src
ON (target.MODULE_CODE = src.MODULE_CODE AND target.ACTION_CODE = src.ACTION_CODE)
WHEN NOT MATCHED THEN
    INSERT (MODULE_CODE, ACTION_CODE, ACTION_DESCRIPTION)
    VALUES (src.MODULE_CODE, src.ACTION_CODE, src.ACTION_DESCRIPTION);

COMMENT ON TABLE HRMS.HRMS_USER_IDENTITIES IS
    'Maps a stable OIDC subject (configured as APEX APP_USER) to one HRMS employee.';
COMMENT ON TABLE HRMS.HRMS_ROLES IS
    'Application roles; role definitions do not grant permissions until role actions are assigned.';
COMMENT ON TABLE HRMS.HRMS_ACTIONS IS
    'Catalog of module/action pairs used by server-side authorization checks.';
COMMENT ON TABLE HRMS.HRMS_ROLE_ACTIONS IS
    'Time-bounded grants from an application role to a module/action pair.';
COMMENT ON TABLE HRMS.HRMS_USER_ROLES IS
    'Time-bounded HRMS employee role assignments; no assignments are seeded by installation.';
COMMENT ON TABLE HRMS.HRMS_EMPLOYEE_SCOPE_DELEGATIONS IS
    'Time-bounded delegations of an employee manager hierarchy.';

